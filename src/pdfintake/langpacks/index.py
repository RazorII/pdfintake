"""The pack index: which language packs this core release knows, and how to get each one.

``index.json`` is generated by ``tools/build_index.py`` from ``packs/*/manifest.json`` and the
reproducibly built wheels, and ships inside the core wheel, so a pack reaches users only through a
core release. Each entry pins the pack's wheel (SHA-256 and size) and its manifest (SHA-256), and
keeps a copy of the manifest's ``detect`` block (``detect_copy``), so detection can use a pack's
function words and OSD scripts before the pack is fetched.

``load`` reads the packaged index strictly and lists every problem at once with its JSON path:
the shape, one base pack shipped with the install, every other pack fetched over HTTPS as a
GitHub release asset of the core repo (``ENTRY_HOST``) under its own wheel name, and nothing newer
than this core.
``url_problems`` holds the rules for an entry's URL; ``redirect_problems`` the looser rule for a
redirect met during a fetch (GitHub's signed asset address carries a query string).
There is no environment override: the ``path`` argument exists for tests only.
"""

from __future__ import annotations

import copy
import functools
import re
import urllib.parse
from collections.abc import Mapping
from dataclasses import dataclass
from importlib import resources
from pathlib import Path
from typing import Any, Literal

from .. import __version__
from ..errors import PackError
from .manifest import BASE_PACK_ID, _dedupe, _freeze, _load_json, _manifest_schema, _Schema, _semver

# The data wheels are GitHub release assets of the core repo (immutable releases). github.com
# answers a release-asset download with a 302 to a signed address on
# release-assets.githubusercontent.com, which serves the file (HEAD requests on two public
# release assets, decided 2026-11-05). A fetch connects only to these hosts and follows redirects
# only within them.
ALLOWED_HOSTS: tuple[str, ...] = ("github.com", "release-assets.githubusercontent.com")
# An index entry names the release download on github.com, never the signed address it redirects
# to (that one carries a query and expires), and it is a release asset of the core repo.
ENTRY_HOST = "github.com"
RELEASES_PATH = "/RazorII/pdfintake/releases/download/"
# Characters an index entry URL may hold: RFC 3986 unreserved, plus ':' and '/'.
_URL_CHARS = re.compile(r"[A-Za-z0-9._~/:-]*")

INDEX_VERSION = 1
MAX_INDEX_BYTES = 1 << 20
MAX_WHEEL_BYTES = 256 * 1024 * 1024
MAX_INSTALLED_BYTES = 1024 * 1024 * 1024


@dataclass(frozen=True)
class Dist:
    kind: Literal["installed", "fetch"]
    distribution: str
    url: str | None
    sha256: str
    bytes: int


@dataclass(frozen=True)
class IndexEntry:
    id: str
    version: str
    base: bool
    title: str
    scripts: tuple[str, ...]
    langid_codes: tuple[str, ...]
    detect: Mapping[str, Any]
    manifest_sha256: str
    dist: Dist
    installed_bytes: int


@dataclass(frozen=True)
class Index:
    version: int
    entries: tuple[IndexEntry, ...]

    def get(self, pack_id: str) -> IndexEntry | None:
        for e in self.entries:
            if e.id == pack_id:
                return e
        return None

    def base(self) -> IndexEntry:
        for e in self.entries:
            if e.base:
                return e
        raise PackError("index_no_base", "the pack index names no base pack")

    def for_script(self, script: str) -> list[IndexEntry]:
        """Packs whose detection answers to this OSD script (``detect.osd_scripts``), in index order."""
        return [e for e in self.entries if script in (e.detect.get("osd_scripts") or ())]

    def for_language(self, code: str) -> list[IndexEntry]:
        """Packs whose language identifier codes include ``code`` (``detect.langid.codes``), in index order."""
        return [e for e in self.entries if code in e.langid_codes]


def detect_copy(detect: Mapping[str, Any]) -> dict[str, Any]:
    """The index's copy of a manifest's ``detect`` block: the same, with ``probe`` reduced to
    whether the pack has one (a probe needs the pack's own models, so it can't run before a fetch)."""
    out = copy.deepcopy({k: v for k, v in detect.items() if k != "probe"})
    out["probe"] = detect.get("probe") is not None
    return out


def wheel_name(distribution: str, version: str) -> str:
    """The file name a pack's wheel is published under."""
    return f"{distribution.replace('-', '_')}-{version}-py3-none-any.whl"


def load(path: Path | None = None) -> Index:
    """The packaged index (``path`` for tests only); PackError naming every problem."""
    if path is None:
        res = resources.files(__package__).joinpath("index.json")
        if not res.is_file():
            raise PackError("index_missing", "this pdfintake install has no pack index (langpacks/index.json); "
                                             "reinstall pdfintake")
        data = res.read_bytes()
    else:
        try:
            data = Path(path).read_bytes()
        except OSError as exc:
            raise PackError("index_missing", f"can't read the pack index {path}: {exc.strerror or exc}") from None
    return _parse(data)


