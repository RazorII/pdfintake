@functools.lru_cache(maxsize=1)
def _index_schema() -> _Schema:
    base = _manifest_schema().root
    defs = dict(base["$defs"])
    detect = copy.deepcopy(defs["detect"])
    detect["properties"]["probe"] = {"type": "boolean"}
    detect["required"] = ["osd_scripts", "probe"]
    defs["detectCopy"] = detect
    props = base["properties"]
    defs["entry"] = {
        "type": "object", "additionalProperties": False,
        "required": ["id", "version", "base", "title", "scripts", "langid_codes", "detect", "manifest_sha256",
                     "dist", "installed_bytes"],
        "properties": {
            "id": props["id"], "version": props["version"], "base": {"type": "boolean"}, "title": props["title"],
            "scripts": props["scripts"],
            "langid_codes": {"type": "array", "maxItems": 4, "uniqueItems": True,
                             "items": {"type": "string", "pattern": "^[a-z]{2,3}$"}},
            "detect": {"$ref": "#/$defs/detectCopy"},
            "manifest_sha256": {"$ref": "#/$defs/sha256"},
            "dist": {"type": "object", "additionalProperties": False,
                     "required": ["kind", "distribution", "url", "sha256", "bytes"],
                     "properties": {
                         "kind": {"enum": ["installed", "fetch"]},
                         "distribution": {"type": "string", "pattern": "^pdfintake-(data|lang)-[a-z]{2,3}(-[a-z0-9]{2,8})?$"},
                         "url": {"type": ["string", "null"], "maxLength": 400},
                         "sha256": {"$ref": "#/$defs/sha256"},
                         "bytes": {"type": "integer", "minimum": 1, "maximum": MAX_WHEEL_BYTES}}},
            "installed_bytes": {"type": "integer", "minimum": 1, "maximum": MAX_INSTALLED_BYTES},
        },
    }
    return _Schema({
        "type": "object", "additionalProperties": False, "required": ["index_version", "core_min", "packs"],
        "properties": {
            "index_version": {"const": INDEX_VERSION},
            "core_min": {"type": "string", "pattern": "^(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)$"},
            "packs": {"type": "array", "minItems": 1, "maxItems": 256, "items": {"$ref": "#/$defs/entry"}},
        },
        "$defs": defs,
    })


def url_problems(url: Any, distribution: str | None = None, version: str | None = None) -> list[str]:
    """Why an index entry's ``dist.url`` is refused ([] when it is allowed).

    This checks the address written in ``index.json`` only: https on ``ENTRY_HOST`` (github.com),
    no user name, port, query, fragment, ``..``, ``%`` or backslash, only RFC 3986 unreserved
    characters plus ``:`` and ``/``, a release asset of the core repo, and (given
    ``distribution`` and ``version``) ending in the wheel's own file name. It is not for a redirect's
    ``Location``: GitHub redirects a release download to a signed address with a query string, which
    this refuses; use ``redirect_problems`` there."""
    if not isinstance(url, str):
        return ["a fetched pack needs a URL"]
    try:
        u = urllib.parse.urlsplit(url)
        port = u.port
    except ValueError:
        return ["isn't a valid URL"]
    out: list[str] = []
    if u.scheme != "https":
        out.append("must use https")
    if u.hostname not in ALLOWED_HOSTS:
        out.append(f"host {u.hostname!r} isn't allowed ({', '.join(ALLOWED_HOSTS)})")
    elif u.hostname != ENTRY_HOST:
        out.append(f"must be the release download on {ENTRY_HOST}; {u.hostname} is only where GitHub "
                   "redirects that download")
    if u.username is not None or u.password is not None or "@" in u.netloc:
        out.append("must not carry a user name or password")
    if port is not None:
        out.append("must not name a port")
    if u.query or "?" in url:
        out.append("has a query string")
    if u.fragment or "#" in url:
        out.append("has a fragment")
    if ".." in url or "%" in url or "\\" in url:
        out.append("contains '..', '%' or a backslash")
    # urlsplit drops tabs and newlines without a word, so the raw string is checked as well.
    stray = sorted({c for c in url if not _URL_CHARS.fullmatch(c) and c not in "?#%\\"})
    if stray:
        out.append("contains a character outside the RFC 3986 unreserved set, ':' and '/' ("
                   + ", ".join(repr(c) for c in stray) + ")")
    if u.hostname == ENTRY_HOST and not u.path.startswith(RELEASES_PATH):
        out.append(f"must be a GitHub release asset under {RELEASES_PATH}")
    if distribution is not None and version is not None:
        want = wheel_name(distribution, version)
        if not u.path.endswith("/" + want):
            out.append(f"must end in /{want}")
    return out


def redirect_problems(url: Any) -> list[str]:
    """Why a fetch may not follow a redirect to ``url`` ([] when it may).

    The rule for a redirect is only that it stays on https on a host in ``ALLOWED_HOSTS`` (§3.5),
    with no user name or port and no whitespace or control characters. A query string is allowed,
    because GitHub signs the release-asset address it redirects to."""
    if not isinstance(url, str) or not url:
        return ["is missing"]
    try:
        u = urllib.parse.urlsplit(url)
        port = u.port
    except ValueError:
        return ["isn't a valid URL"]
    out: list[str] = []
    if u.scheme != "https":
        out.append("must use https")
    if u.hostname not in ALLOWED_HOSTS:
        out.append(f"host {u.hostname!r} isn't allowed ({', '.join(ALLOWED_HOSTS)})")
    if u.username is not None or u.password is not None or "@" in u.netloc:
        out.append("must not carry a user name or password")
    if port is not None:
        out.append("must not name a port")
    if any(ord(c) <= 0x20 or ord(c) >= 0x7F or c == "\\" for c in url):
        out.append("contains whitespace, a control character, a non-ASCII character or a backslash")
    return out


def _parse(data: bytes) -> Index:
    raw = _load_json(data, "pack index", "invalid_index", MAX_INDEX_BYTES)
    problems = _index_schema().problems(raw)
    problems.extend(_semantic(raw))
    problems = _dedupe(problems)
    if problems:
        raise PackError("invalid_index",
                        f"the pack index is invalid ({len(problems)} problem{'s' if len(problems) != 1 else ''}): "
                        + "; ".join(problems), problems=problems)
    entries = []
    for e in raw["packs"]:
        d = e["dist"]
        langid = e["langid_codes"]
        entries.append(IndexEntry(
            id=e["id"], version=e["version"], base=e["base"], title=e["title"], scripts=tuple(e["scripts"]),
            langid_codes=tuple(langid), detect=_freeze(e["detect"]), manifest_sha256=e["manifest_sha256"],
            dist=Dist(d["kind"], d["distribution"], d["url"], d["sha256"], int(d["bytes"])),
            installed_bytes=int(e["installed_bytes"])))
    return Index(int(raw["index_version"]), tuple(entries))


def _semantic(raw: Mapping[str, Any]) -> list[str]:
    from ..ocr import scripts

    out: list[str] = []
    need, have = _semver(raw.get("core_min")), _semver(__version__)
    if need is not None and have is not None and need > have:
        out.append(f"$.core_min: this index needs pdfintake {raw['core_min']} or newer; this is {__version__}")
    packs = raw.get("packs") if isinstance(raw.get("packs"), list) else []
    seen: set[str] = set()
    bases: list[int] = []
    for i, e in enumerate(packs):
        if not isinstance(e, Mapping):
            continue
        path = f"$.packs[{i}]"
        pid = e.get("id")
        if isinstance(pid, str):
            if pid in seen:
                out.append(f"{path}.id: {pid!r} is listed twice")
            seen.add(pid)
        is_base = e.get("base") is True
        if is_base:
            bases.append(i)
            if pid != BASE_PACK_ID:
                out.append(f"{path}.base: only the base pack ({BASE_PACK_ID!r}) may set base: true")
        elif pid == BASE_PACK_ID:
            out.append(f"{path}.base: the {BASE_PACK_ID!r} pack is the base pack and must set base: true")
        for j, s in enumerate(e.get("scripts") or () if isinstance(e.get("scripts"), list) else ()):
            if isinstance(s, str) and s not in scripts.SCRIPTS:
                out.append(f"{path}.scripts[{j}]: {s!r} is not a script this core knows")
        detect = e.get("detect")
        if isinstance(detect, Mapping):
            for j, s in enumerate(detect.get("osd_scripts") or () if isinstance(detect.get("osd_scripts"), list) else ()):
                if isinstance(s, str) and s not in scripts.SCRIPTS:
                    out.append(f"{path}.detect.osd_scripts[{j}]: {s!r} is not a script this core knows")
            langid = detect.get("langid")
            codes = list(langid.get("codes") or []) if isinstance(langid, Mapping) else []
            if isinstance(e.get("langid_codes"), list) and list(e["langid_codes"]) != codes:
                out.append(f"{path}.langid_codes: must equal detect.langid.codes ({codes})")
        d = e.get("dist")
        if not isinstance(d, Mapping):
            continue
        dist_name = d.get("distribution")
        if isinstance(pid, str) and isinstance(dist_name, str):
            want = f"pdfintake-{'data' if is_base else 'lang'}-{pid}"
            if dist_name != want:
                out.append(f"{path}.dist.distribution: must be {want!r}")
        if is_base:
            if d.get("kind") != "installed":
                out.append(f"{path}.dist.kind: the base pack ships with the install (kind installed)")
            if d.get("url") is not None:
                out.append(f"{path}.dist.url: an installed pack has no URL (null)")
        else:
            if d.get("kind") != "fetch":
                out.append(f"{path}.dist.kind: only the base pack is installed; every other pack is fetched")
            version = e.get("version") if isinstance(e.get("version"), str) else None
            for reason in url_problems(d.get("url"), dist_name if isinstance(dist_name, str) else None, version):
                out.append(f"{path}.dist.url: {reason}")
    if packs and len(bases) != 1:
        out.append(f"$.packs: exactly one pack must be the base pack (found {len(bases)})")
    return out

